"""Ports: the small interfaces the application layer depends on (dependency inversion + interface segregation).
Infrastructure provides the implementations; tests provide in-memory fakes."""
from __future__ import annotations

from typing import Any, Protocol, Sequence

from .models import (Association, CaseStudy, Dataset, DatasetAvailability, Intervention, Investigation, Mechanism,
                     Region, SeasonPoint, TrendStats, Variable)


class CatalogueReader(Protocol):
    def regions(self) -> list[Region]: ...
    def region(self, code: str) -> Region | None: ...
    def datasets(self) -> list[dict[str, Any]]: ...                 # with observation counts, for the catalogue screen
    def dataset(self, code: str) -> Dataset | None: ...
    def variables(self) -> list[Variable]: ...
    def variable(self, code: str) -> Variable | None: ...


class ObservationReader(Protocol):
    def availability(self, region: str, variable: str) -> list[DatasetAvailability]: ...
    def season_series(self, region: str, variable: str, dataset: str, year_start: int, year_end: int) -> list[SeasonPoint]: ...
    def series(self, region: str, variable: str, dataset: str, grain: str) -> list[dict[str, Any]]: ...
    def recent_seasons(self, region: str, variable: str, from_year: int) -> list[dict[str, Any]]: ...


class PrecomputedTrendReader(Protocol):
    def trends(self, variable: str | None, region: str | None, dataset: str | None) -> list[dict[str, Any]]: ...


class MechanismReader(Protocol):
    def mechanisms(self) -> list[Mechanism]: ...
    def evidence_ids(self) -> set[str]: ...


class CaseStudyReader(Protocol):
    def case_studies(self, region: str | None) -> list[CaseStudy]: ...


class BuildInfoReader(Protocol):
    def latest(self) -> dict[str, Any] | None: ...


class DatasetReferenceReader(Protocol):
    def references(self) -> list[dict[str, Any]]: ...


class EvidenceLedgerReader(Protocol):
    """Rows of the scientific evidence ledger (docs/research/evidence_ledger.md, loaded into dim_evidence)."""
    def evidence(self, ids: list[str] | None) -> list[dict[str, Any]]: ...


class InterventionCatalogue(Protocol):
    def all(self) -> list[Intervention]: ...


class InvestigationRepository(Protocol):
    def next_id(self) -> str: ...
    def save(self, investigation: Investigation) -> Investigation: ...
    def get(self, investigation_id: str) -> Investigation | None: ...
    def list(self) -> list[dict[str, Any]]: ...


class InvestigationHousekeeping(Protocol):
    def count(self) -> int: ...
    def purge_older_than(self, iso_timestamp: str) -> int: ...


class TrendAnalyzer(Protocol):
    def analyze(self, series: dict[int, float], full: bool = True) -> TrendStats:
        """full=False: Mann-Kendall + Sen only (no OLS/AR(1) cross-checks); for sensitivity tables and side checks."""
        ...


class AssociationAnalyzer(Protocol):
    def detrended(self, x: dict[int, float], y: dict[int, float]) -> Association: ...


class ChatModel(Protocol):
    """OpenAI-compatible chat completion with tool calling. Returns the assistant message:
    {"content": str | None, "tool_calls": [{"id", "function": {"name", "arguments"}}] | None}."""
    model_name: str

    def complete(self, messages: list[dict[str, Any]], tools: list[dict[str, Any]]) -> dict[str, Any]: ...


class Clock(Protocol):
    def now(self) -> str: ...

